function resolvePlanMessage(key, fallbackOrSubstitutions, maybeSubstitutions) {
  const hasExplicitFallback = maybeSubstitutions !== undefined;
  const fallback = hasExplicitFallback ? fallbackOrSubstitutions : (PLAN_MESSAGES[key] || key);
  const substitutions = hasExplicitFallback ? maybeSubstitutions : fallbackOrSubstitutions;

  return getUiMessage(key, PLAN_MESSAGES[key] || fallback, substitutions);
}

export function getMessage(key, fallbackOrSubstitutions, maybeSubstitutions) {
  return resolvePlanMessage(key, fallbackOrSubstitutions, maybeSubstitutions);
}

export function getPlanMessage(key, fallbackOrSubstitutions, maybeSubstitutions) {
  return resolvePlanMessage(key, fallbackOrSubstitutions, maybeSubstitutions);
}
